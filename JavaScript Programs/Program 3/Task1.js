// Grocery List Manager

let groceryList = [];
// Adding Milk to the grocery list
groceryList.push("Milk");
console.log(groceryList);
// Milk is added

// Adding Eggs to the grocery list
groceryList.push("Eggs")
console.log(groceryList);
// Eggs are added

// Adding Bread to the grocery list
groceryList.push("Bread");
console.log(groceryList);
// Bread is added

// Removing last item
groceryList.pop();
console.log(groceryList);
// last item remove

// Adding Fruits to the beginning
groceryList.unshift("Fruits");
console.log(groceryList);
// Fruits added to the beginning

// Removing First item from the grocery list
groceryList.shift()
console.log(groceryList);
// First item is removed and the final list is printed